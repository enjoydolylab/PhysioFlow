import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createPhysioDBBindings } from '../server/physioDBBindings.mjs';
import { createHostedNodeServer } from '../server/createHostedNodeServer.mjs';
import { createPhysioDBServiceClient } from '../src/physioDBServiceClient.js';
const ids = [1, 2, 3, 4, 5].map(i => `00000000-0000-4000-8000-${String(i).padStart(12, '0')}`);
const target = { sessionId: 'pf-session', protocolId: 'pf-protocol', protocolVersion: 1, researchId: ids[0], experimentId: ids[1], participantId: ids[2], streamIds: [ids[3]] };
const actor = { actorId: 'owner', tenantId: 'default' };
const bridge = async (_, operation) => ({ researches: [{ id: ids[0] }], experiments: [{ id: ids[1] }], participants: [{ id: ids[2] }], streams: [{ id: ids[3], experiment_id: ids[1], participant_id: ids[2] }] })[operation];
test('bindings validate ownership, reject remapping, survive restart and isolate actors/tenants', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'pf-bind-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const filePath = join(dir, 'bindings.json');
  const store = await createPhysioDBBindings({ filePath, bridge });
  await assert.rejects(store.put(actor, { ...target, streamIds: [ids[4]] }), /do not belong/);
  assert.deepEqual(await store.list(actor), []);
  const [a, b] = await Promise.all([store.put(actor, target), store.put(actor, target)]);
  assert.deepEqual(a, b); assert.equal((await store.list(actor)).length, 1);
  await assert.rejects(store.put(actor, { ...target, participantId: ids[4] }), e => e.status === 409);
  const restored = await createPhysioDBBindings({ filePath, bridge });
  assert.deepEqual(await restored.list(actor), [a]);
  assert.deepEqual(await restored.list({ ...actor, tenantId: 'other' }), []);
  assert.deepEqual(await restored.list({ ...actor, actorId: 'another' }), []);
  await assert.rejects(store.put(actor, { ...target, sessionId: 'another', token: 'should-never-be-persisted' }), e => e.status === 400);
});
test('binding endpoints enforce owner authorization and persist through client', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'pf-bind-http-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const server = await createHostedNodeServer({ actors: [{ ...actor, role: 'owner', accessToken: 'owner' }, { actorId: 'viewer', role: 'viewer', accessToken: 'viewer' }, { ...actor, tenantId: 'other', role: 'owner', accessToken: 'other' }], credentialKeys: [{ keyId: 'test', secret: 'binding-test-credential-secret-at-least-32-characters' }], stateFile: join(dir, 'state.json'), physioDBBridge: bridge });
  const { baseUrl } = await server.listen(0); t.after(() => server.close());
  const client = accessToken => createPhysioDBServiceClient({ baseUrl, accessToken });
  await assert.rejects(client('viewer').bindSession(target), e => e.status === 403);
  await assert.rejects(client('invalid').bindings(), e => e.status === 403);
  server.service.participantTokens.set('participant', { active: true, sessionId: target.sessionId, participantId: 'P01', tenantId: 'default' });
  await assert.rejects(client('participant').bindings(), e => e.status === 403);
  await assert.rejects(client('participant').bindSession(target), e => e.status === 403);
  server.service.sessions.set('hosted_session', { sessionId: 'hosted_session', tenantId: 'other', protocolId: target.protocolId, protocolVersion: 1 });
  await assert.rejects(client('owner').bindSession({ ...target, sessionId: 'hosted_session' }), e => e.status === 404);
  await assert.rejects(client('other').bindSession({ ...target, sessionId: 'hosted_session', protocolVersion: 2 }), e => e.status === 400);
  const saved = await client('owner').bindSession(target);
  assert.equal(saved.syncStatus, 'binding_only');
  assert.deepEqual(await client('owner').bindings(), [saved]);
  assert.deepEqual(await client('other').bindings(), []);
  await assert.rejects(client('owner').bindSession({ ...target, protocolVersion: 2 }), e => e.status === 409);
});
