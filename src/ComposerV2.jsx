import { useEffect, useMemo, useState } from 'react';
import ParticipantUiBuilder from './ParticipantUiBuilder.jsx';
import { updateNode, assignNodeToGroup, createNodeGroup } from './core/index.js';
import { localResourceManifest, schemaForNode } from './runtime/index.js';
import { UI_TEMPLATE_KIND } from './composer/toolbox.js';
import { CodeView } from './composer/NodeInspector.jsx';
import { useComposerState } from './composer/useComposerState.js';
import Header from './composer/Header.jsx';
import GuidePanel from './GuidePanel.jsx';
import { useGuideCopy } from './TaskGuide.jsx';
import { previewResourceIds } from './composer/mediaPerformance.js';
import Palette from './composer/Palette.jsx';
import Canvas from './composer/Canvas.jsx';
import Sequence from './composer/Sequence.jsx';
import { protocolSequence } from './composer/sequenceModel.js';
import Inspector from './composer/Inspector.jsx';
import ProtocolBioDBConfig from './ProtocolBioDBConfig.jsx';
import { loadSettings, loadAssetFile } from './fsStorage.js';

export default function ComposerV2({ protocol, onChange, onSave, onBack, onExport, onPreview, onFreeze, onCreateDraft, onHostedRun, onUndo, onRedo, canUndo, canRedo, hasUnsaved, saveAnim }) {
  const [guideOpen, setGuideOpen] = useState(false);
  const guide = useGuideCopy();
  const s = useComposerState({ protocol, onChange });
  const {
    t, locked, codeView, codeText, codeError,
    deletePending, confirmDelete, cancelDelete,
    previewNode, previewDefinition, setPreviewNodeId,
    actions, setCodeText, applyCode, closeCodeView, formatCode, codeDirty,
  } = s;
  const [flowView, setFlowView] = useState(null);
  const ordered = protocolSequence(protocol);
  const sequenceVisible = ordered && (flowView === 'sequence' || (!flowView && s.editorMode === 'quick'));
  const [bioDBOpen, setBioDBOpen] = useState(false);
  const [settings, setSettings] = useState(null);
  const previewIds = previewResourceIds(protocol, [s.selectedNode, previewNode]);
  const previewAssetKey = JSON.stringify((protocol.assets || []).filter(asset => previewIds.has(asset.id || asset.assetId)));
  const previewAssets = useMemo(() => JSON.parse(previewAssetKey), [previewAssetKey]);
  const [previewResources, setPreviewResources] = useState(() => localResourceManifest(protocol.assets || []));
  useEffect(() => {
    if (bioDBOpen) loadSettings().then(setSettings).catch(() => setSettings({}));
  }, [bioDBOpen]);
  useEffect(() => {
    let active = true;
    const objectUrls = [];
    Promise.all(previewAssets.map(async asset => {
      if (asset.sourceUrl || asset.url) return null;
      const assetId = asset.id || asset.assetId;
      const stored = await loadAssetFile(assetId);
      if (!active || !stored?.file) return null;
      const url = URL.createObjectURL(stored.file);
      objectUrls.push(url);
      return { assetId, name: asset.name || stored.name || assetId, mediaType: asset.mediaType || stored.type?.split('/')[0] || null, status: 'ready', delivery: { url } };
    })).then(resources => { if (active) setPreviewResources([...localResourceManifest(previewAssets), ...resources.filter(Boolean)]); }).catch(() => {});
    return () => { active = false; objectUrls.forEach(url => URL.revokeObjectURL(url)); };
  }, [previewAssets]);
  // Questionnaire and Wait screens are generated by the runtime schema (their builder
  // edits would be discarded), so their full-screen editor is preview-only.
  const fullscreenUiEditable = previewNode && !['input.questionnaire', 'timing.wait'].includes(previewNode.component.type);
  return <main className={`composer-v2 ${locked ? 'locked' : ''}`}>
    <Header s={s} onSave={onSave} onBack={onBack} onExport={onExport} onPreview={onPreview} onFreeze={onFreeze} onCreateDraft={onCreateDraft} onUndo={onUndo} onRedo={onRedo} canUndo={canUndo} canRedo={canRedo} hasUnsaved={hasUnsaved} saveAnim={saveAnim} onGuide={() => setGuideOpen(true)} onBioDB={() => setBioDBOpen(true)} />
    {!locked && protocol.graph.nodes.length <= 2 && <p className="composer-first-step">{guide.hint}</p>}
    {bioDBOpen && <ProtocolBioDBConfig protocol={protocol} settings={settings || {}} onChange={onChange} onClose={() => setBioDBOpen(false)} />}
    {deletePending && <div className="composer-delete-confirm">{t('Delete {n} node(s)? You can undo this change.').replace('{n}', deletePending.ids.length)}
      <button className="danger" onClick={confirmDelete}>{t('Delete')}</button>
      <button onClick={cancelDelete}>{t('Cancel')}</button>
    </div>}
    {guideOpen && <GuidePanel onClose={() => setGuideOpen(false)} />}
    {codeView ? <CodeView text={codeText} error={codeError} locked={locked} dirty={codeDirty} onChange={setCodeText} onApply={applyCode} onFormat={formatCode} onClose={closeCodeView} /> : <div className="composer-layout">
      <Palette s={s} sequence={Boolean(sequenceVisible)} onHostedRun={onHostedRun} />
      {sequenceVisible ? <Sequence s={s} ordered={ordered} onGraph={() => setFlowView('graph')} /> : <div className="composer-graph-view">{ordered && <button className="sequence-view-toggle" onClick={() => setFlowView('sequence')}>{s.t('Sequence view')}</button>}<Canvas s={s} /></div>}
      <Inspector s={s} resources={previewResources} />
    </div>}
    {previewNode && <NodeEditor key={previewNode.id} s={s} node={previewNode} definition={previewDefinition} resources={previewResources} editable={fullscreenUiEditable} ordered={ordered} onSave={() => onSave(protocol)} hasUnsaved={hasUnsaved} saveAnim={saveAnim} onClose={() => setPreviewNodeId(null)} onUiChange={actions.updatePreviewUi} />}
  </main>;
}

function NodeEditor({ s, node, definition, resources, editable, ordered, onSave, hasUnsaved, saveAnim, onClose, onUiChange }) {
  // A keyed editor owns its tabs; opening or navigating starts a fresh session.
  const [tab, setTab] = useState(() => (node.config?.ui && editable) ? 'screen' : 'settings');
  const { t, locked, protocol } = s;
  const index = ordered?.findIndex(item => item.id === node.id) ?? -1;
  const inspectorState = { ...s, selectedNode: node, selectedEdge: null,
    updateSelected: patch => s.commit(updateNode(protocol, node.id, patch)),
    actions: { ...s.actions,
      assignNodeToGroup: groupId => s.commit(assignNodeToGroup(protocol, node.id, groupId)),
      createGroupFromSelection: () => s.commit(createNodeGroup(protocol, [node.id], { name: node.label }).protocol),
    } };
  return <div className="node-editor-fullscreen" role="dialog" aria-modal="true" aria-label={node.label}>
    <div className="node-editor-header">
      <button aria-label={t('Previous step')} disabled={index <= 0} onClick={() => s.setPreviewNodeId(ordered[index - 1].id)}>‹</button>
      <button aria-label={t('Next step')} disabled={index < 0 || index >= ordered.length - 1} onClick={() => s.setPreviewNodeId(ordered[index + 1].id)}>›</button>
      <b>{node.label}</b>
      <div role="tablist" aria-label={t('Node editor')}>
        <button role="tab" aria-selected={tab === 'settings'} onClick={() => setTab('settings')}>{t('Settings')}</button>
        <button role="tab" aria-selected={tab === 'screen'} onClick={() => setTab('screen')}>{t('Screen')}</button>
      </div>
      {hasUnsaved && <small className="unsaved-dot" aria-label={t('Unsaved changes')}>●</small>}
      <button className={saveAnim ? 'saved' : ''} onClick={onSave}>{t('Save')}</button>
      <button className="node-editor-close" onClick={onClose}>{t('✕ Done')}</button>
    </div>
    <div className="node-editor-body" role="tabpanel">
      {tab === 'settings' ? <Inspector s={inspectorState} resources={resources} nodeOnly onEditParticipantUi={() => setTab('screen')} />
        : editable ? <fieldset disabled={locked} className="node-editor-screen"><ParticipantUiBuilder schema={schemaForNode(node, definition, resources)} defaultTemplate={UI_TEMPLATE_KIND[node.component.type] || 'instruction'} onChange={onUiChange} /></fieldset>
        : <p>{t('This screen is generated automatically; edit its settings in the Settings tab.')}</p>}
    </div>
  </div>;
}
